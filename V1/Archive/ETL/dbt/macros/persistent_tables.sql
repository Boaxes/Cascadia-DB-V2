{#
  The tables the build reads but never drops, and never rebuilds.

  In raw, beside DB167's own tables (which import_raw.py owns), the other
  inputs to the build:

      raw.species           the species list: stable ids, names people curate
      raw.event_code_name   a short display name for each daily event code
      raw.vessel_list       the vessel list: stable ids, one row per vessel text
      raw.track_geometry    one row per GPS file in the bucket: its line

  and in app, what the website writes:

      app.audit_log         every change made through the website, and app.record_diff()

  Each has a single writer. The lists are edited directly; the build adds
  codes and vessel texts it has not seen, and an id never moves once given.
  raw.track_geometry is written only by Django/datahealth/gps/tracks.py, when
  a file is uploaded or regenerated. None of them carries raw's frozen trigger:
  that is for DB167's tables only.

  Everything here is create-if-missing, so running it against a database that
  already has these tables changes nothing. It runs at the start of every dbt
  invocation (on-run-start) and can be run on its own:

      dbt run-operation create_persistent_tables
#}
{% macro persistent_tables_sql() %}
        CREATE EXTENSION IF NOT EXISTS postgis;
        CREATE SCHEMA IF NOT EXISTS raw;
        CREATE SCHEMA IF NOT EXISTS app;

        -- The website's record of every change (Django/datahealth/audit.py).
        -- The build replays it; nothing else writes it.
        CREATE TABLE IF NOT EXISTS app.audit_log (
            id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
            occurred_at  timestamptz NOT NULL DEFAULT now(),
            actor_id     integer,                -- auth_user.id; no FK, Django owns that table
            actor_name   text NOT NULL,          -- denormalised, survives user deletion
            action       text NOT NULL
                CHECK (action IN ('create','update','delete','restore',
                                  'upload','associate','dissociate')),
            target_table text NOT NULL,          -- the dbo table, not the app view
            target_pk    text,
            changes      jsonb,                  -- {"field": {"old": ..., "new": ...}}
            snapshot     jsonb,                  -- {"TableName": [row, ...]} on delete
            comment      text,
            restored_by  bigint REFERENCES app.audit_log(id)
        );

        CREATE INDEX IF NOT EXISTS ix_audit_target ON app.audit_log (target_table, target_pk);
        CREATE INDEX IF NOT EXISTS ix_audit_actor  ON app.audit_log (actor_id, occurred_at DESC);
        CREATE INDEX IF NOT EXISTS ix_audit_time   ON app.audit_log (occurred_at DESC);

        CREATE TABLE IF NOT EXISTS raw.species (
            species_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            code            text NOT NULL UNIQUE,
            common_name     text,
            scientific_name text,
            category        text NOT NULL DEFAULT 'unidentified'
        );
        COMMENT ON TABLE raw.species IS
            'The species list. Every species code used in a sighting has a row; '
            'names and categories are curated here. An id never changes once given.';

        CREATE TABLE IF NOT EXISTS raw.event_code_name (
            code text PRIMARY KEY,
            name text NOT NULL
        );
        COMMENT ON TABLE raw.event_code_name IS
            'A short display name for each daily event code. DB167''s EventCodeT '
            'describes each code as an instruction to the crew; this is what the '
            'application shows instead.';

        CREATE TABLE IF NOT EXISTS raw.vessel_list (
            vessel_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            vessel_text      text NOT NULL UNIQUE,
            code             text,
            name             text,
            legacy_vessel_id integer
        );
        COMMENT ON TABLE raw.vessel_list IS
            'One row per distinct vessel text in the survey tables, with DB167''s '
            'VesselT code and name where the text matches one. An id never changes once given.';

        CREATE TABLE IF NOT EXISTS raw.track_geometry (
            object_key  text PRIMARY KEY,
            etag        text,
            geom        geometry(MultiLineString, 4326),
            point_count integer,
            length_nm   numeric(12,3),
            built_at    timestamptz NOT NULL DEFAULT now()
        );
        COMMENT ON TABLE raw.track_geometry IS
            'One row per GPS file in the bucket. A row existing means the file is '
            'stored. Written only by gps/tracks.py, when a file is uploaded or its '
            'line regenerated; the build never rebuilds it.';

        -- A raw row against its dbo row, field by field, for the history window.
        -- Replaced in place, never dropped: the website calls it.
CREATE OR REPLACE FUNCTION app.record_diff(target_table text, target_pk text)
RETURNS TABLE (field text, original text, current text)
LANGUAGE plpgsql STABLE AS $$
DECLARE
    key_column text;
    raw_row    jsonb;
    dbo_row    jsonb;
BEGIN
    SELECT a.attname INTO key_column
    FROM   pg_index i
    JOIN   pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
    WHERE  i.indrelid = format('dbo.%I', target_table)::regclass AND i.indisprimary;

    EXECUTE format('SELECT to_jsonb(t) FROM raw.%I t WHERE %I::text = $1',
                   target_table, key_column) INTO raw_row USING target_pk;
    EXECUTE format('SELECT to_jsonb(t) FROM dbo.%I t WHERE %I::text = $1',
                   target_table, key_column) INTO dbo_row USING target_pk;

    IF raw_row IS NULL THEN
        RETURN;                     -- added after the import; nothing to compare
    END IF;

    RETURN QUERY
    SELECT r.key,
           r.value,
           CASE WHEN dbo_row IS NULL THEN NULL ELSE dbo_row ->> r.key END
    FROM   jsonb_each_text(raw_row) r
    WHERE  dbo_row IS NULL                      -- the row was deleted
       OR (dbo_row ? r.key AND dbo_row ->> r.key IS DISTINCT FROM r.value)
    ORDER  BY r.key;
END;
$$;
{% endmacro %}


{% macro create_persistent_tables() %}
    {% do run_query(persistent_tables_sql()) %}
{% endmacro %}


{#
  One-time, at migration: fill the lists from the dbo tables the old pipeline
  built, keeping every id exactly as it is. A table that already has rows is
  left alone, so this can be run again safely.

      dbt run-operation seed_lists_from_dbo

  raw.track_geometry is seeded separately, because it needs the bucket listing:
      python manage.py regenerate_track_geometry --seed-from-dbo
#}
{% macro seed_lists_from_dbo() %}
    {% do create_persistent_tables() %}
    {% set sql %}
        INSERT INTO raw.species (species_id, code, common_name, scientific_name, category)
        SELECT species_id, code, common_name, scientific_name, category
        FROM   dbo."SpeciesT"
        WHERE  NOT EXISTS (SELECT 1 FROM raw.species);
        SELECT setval(pg_get_serial_sequence('raw.species', 'species_id'),
                      greatest((SELECT max(species_id) FROM raw.species), 1));

        INSERT INTO raw.event_code_name (code, name)
        SELECT "EventCode", name
        FROM   dbo."EventCodeT"
        WHERE  name IS NOT NULL
          AND  NOT EXISTS (SELECT 1 FROM raw.event_code_name);

        INSERT INTO raw.vessel_list (vessel_id, vessel_text, code, name, legacy_vessel_id)
        SELECT vessel_id, vessel_text, code, name, legacy_vessel_id
        FROM   dbo."VesselListT"
        WHERE  NOT EXISTS (SELECT 1 FROM raw.vessel_list);
        SELECT setval(pg_get_serial_sequence('raw.vessel_list', 'vessel_id'),
                      greatest((SELECT max(vessel_id) FROM raw.vessel_list), 1));
    {% endset %}
    {% do run_query(sql) %}
    {% set counts = run_query("SELECT (SELECT count(*) FROM raw.species), (SELECT count(*) FROM raw.event_code_name), (SELECT count(*) FROM raw.vessel_list)") %}
    {% do log("raw.species " ~ counts[0][0] ~ ", raw.event_code_name " ~ counts[0][1] ~ ", raw.vessel_list " ~ counts[0][2] ~ " rows", info=true) %}
{% endmacro %}
