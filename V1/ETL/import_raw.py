"""
Import DB167 into the `raw` schema.

`raw` is a frozen snapshot of the source database: the same tables, the same
columns, the same names, the same values. The only thing that changes is the
type, because SQL Server's types and Postgres's are spelled differently, and
that mapping is one for one.

Postgres accepts DB167's names exactly as they stand -- `"SightingT"`,
`"Research Group"`, `"% Cloud Cover"`, `"Photos?"` -- so they are kept. It also
keeps `"Field ID"` and `"FieldID"` apart, which a lowercase rewrite would have
collapsed into one name and forced us to invent a rule for.

    python import_raw.py --schema     write ETL/schema/raw.sql from DB167
    python import_raw.py              create the schema, then copy the data
    python import_raw.py --verify     compare Postgres against DB167

DB167 is read only. Nothing here writes to it.
"""

import argparse
import hashlib
import os
import pathlib
import sys
import time

import psycopg
from dotenv import load_dotenv

import source

SCHEMA_FILE = pathlib.Path(__file__).parent / "schema" / "raw.sql"

# raw also holds the build's other inputs, which are not DB167's and which an
# import must leave alone: the lists people curate and each GPS file's line
# (ETL/dbt/macros/persistent_tables.sql). An import replaces DB167's tables one
# by one rather than dropping the schema, so these survive it.
BUILD_INPUTS = {"species", "event_code_name", "vessel_list", "track_geometry"}

# DB167's types are already correct. V1 saw text everywhere only because it read
# CSV exports rather than the database. Anything outside this list stops the
# import rather than being guessed at.
TYPES = {
    "int": "integer",
    "smallint": "smallint",
    "bit": "boolean",
    "float": "double precision",
    "date": "date",
    "datetime": "timestamp",
    "time": "time",
    "nvarchar": "text",
    "ntext": "text",
    "binary": "bytea",
}

# The deprecated large types cannot be aggregated or sorted, so they are read
# and compared as ordinary text.
NTEXT_CAST = 'CAST([{col}] AS nvarchar(max))'

# DB167's collation, SQL_Latin1_General_CP1_CI_AS, is case insensitive, and SQL
# Server ignores trailing spaces when it compares text even under a binary
# collation. Postgres does neither. So a distinct count taken naively disagrees
# with Postgres wherever values differ only in case or in trailing space, and
# there are plenty: SightingT.Species has 124 distinct values as the source sees
# them and 162 as Postgres does. Forcing case to matter, and moving a trailing
# space into the middle of the string where SQL Server has to see it, makes the
# two comparable. Those 38 variants are real, and they stay in `raw`.
BIN_COLLATE = "COLLATE Latin1_General_BIN2"
SENTINEL = "N'|'"


def pg_type(column):
    try:
        return TYPES[column["type"]]
    except KeyError:
        raise ValueError(
            f"no mapping for DB167 type {column['type']!r} on column {column['name']!r}"
        )


def primary_key(conn, table, columns):
    """
    The declared primary key, or the one the data supports.

    Two tables declare none. CRC_Vessels_ByYear_T has an identity column that is
    already unique and not null across all 323 rows; TrackFileList is a single
    filename column, 1,479 distinct over 1,479 rows. Both were checked against
    the live data.
    """
    declared = source.primary_key(conn, table)
    if declared:
        return declared
    identity = [c["name"] for c in columns if c["is_identity"]]
    return identity or [columns[0]["name"]]


# ---------------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------------


def build_schema(conn):
    out = [
        "-- Generated by ETL/import_raw.py --schema. Do not edit by hand.",
        "--",
        "-- A frozen snapshot of DB167, with its own names and its own values.",
        "-- Primary keys only: nothing queries this schema, so it needs no other",
        "-- indexes, and DB167 declares no foreign keys -- every relationship in",
        "-- it is by convention, and the data does not satisfy them. 372 research",
        "-- group codes in SightingT have no row in ResearchGroupT, for one.",
        "-- Those are inferred, seeded and enforced in `dbo`, where they can be",
        "-- corrected and the correction recorded. `raw` takes the data as it is.",
        "",
        "-- Only DB167's tables are replaced. raw also holds the build's other",
        "-- inputs (the curated lists and the GPS lines), which an import leaves",
        "-- alone.",
        "CREATE SCHEMA IF NOT EXISTS raw;",
        "",
    ]

    for table in source.tables(conn):
        columns = source.columns(conn, table)
        lines = []
        for column in columns:
            null = "" if column["nullable"] else " NOT NULL"
            # SightingT's three hash columns are persisted SHA-256 values over
            # Research Group, Vessel and Sighting, added in DB167 to index the
            # natural key. They are copied as ordinary columns -- Postgres would
            # not maintain them, and `raw` never changes anyway.
            note = "  -- computed in DB167" if column["is_computed"] else ""
            lines.append(f'    "{column["name"]}" {pg_type(column)}{null},{note}')
        pk = ", ".join(f'"{c}"' for c in primary_key(conn, table, columns))
        lines.append(f"    PRIMARY KEY ({pk})")
        out.append(f'DROP TABLE IF EXISTS raw."{table}" CASCADE;')
        out.append(f'CREATE TABLE raw."{table}" (')
        out.append("\n".join(lines))
        out.append(");")
        out.append("")

    out += [
        "-- Freeze. A REVOKE does not bind the table owner; a trigger does.",
        "CREATE OR REPLACE FUNCTION raw.frozen() RETURNS trigger LANGUAGE plpgsql AS $$",
        "BEGIN",
        "    RAISE EXCEPTION 'raw.% is a frozen snapshot of DB167 and cannot be "
        "changed', TG_TABLE_NAME;",
        "END;",
        "$$;",
        "",
    ]
    for table in source.tables(conn):
        out.append(
            f'CREATE TRIGGER "{table}_frozen" BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE\n'
            f'    ON raw."{table}" FOR EACH STATEMENT EXECUTE FUNCTION raw.frozen();'
        )
    out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Load
# ---------------------------------------------------------------------------


def load(conn, dst):
    ddl, freeze = SCHEMA_FILE.read_text().split("-- Freeze.", 1)
    with dst.cursor() as cur:
        cur.execute(ddl)
    dst.commit()
    print(f"created raw from {SCHEMA_FILE.name}")

    total = 0
    for table in source.tables(conn):
        names = [c["name"] for c in source.columns(conn, table)]
        target = ", ".join(f'"{n}"' for n in names)
        started, count = time.time(), 0
        with dst.cursor() as cur:
            with cur.copy(f'COPY raw."{table}" ({target}) FROM STDIN') as copy:
                for batch in source.rows(conn, table, names):
                    for row in batch:
                        copy.write_row(tuple(row))
                        count += 1
        dst.commit()
        total += count
        print(f"  {table:<28} {count:>8,} rows  {time.time() - started:5.1f}s")

    with dst.cursor() as cur:
        cur.execute("-- Freeze." + freeze)
    dst.commit()
    print(f"copied {total:,} rows, then froze raw")


# ---------------------------------------------------------------------------
# Verify
#
# The gate. Everything is measured on both sides and compared, so nothing is
# assumed to have worked because the copy did not raise.
# ---------------------------------------------------------------------------


def _source_stats(conn, table, columns):
    parts = []
    for column in columns:
        ref = (
            NTEXT_CAST.format(col=column["name"])
            if column["type"] == "ntext"
            else f'[{column["name"]}]'
        )
        distinct = ref
        if pg_type(column) == "text":
            distinct = f"(CAST({ref} AS nvarchar(max)) + {SENTINEL}) {BIN_COLLATE}"
        parts.append(f"count({ref})")
        parts.append(f"count(DISTINCT {distinct})")
    row = conn.execute(f"SELECT count(*), {', '.join(parts)} FROM dbo.[{table}]").fetchone()
    return row[0], {
        c["name"]: {"filled": row[1 + i * 2], "distinct": row[2 + i * 2]}
        for i, c in enumerate(columns)
    }


def _target_stats(dst, table, columns):
    parts = []
    for column in columns:
        parts.append(f'count("{column["name"]}")')
        parts.append(f'count(DISTINCT "{column["name"]}")')
    with dst.cursor() as cur:
        cur.execute(f'SELECT count(*), {", ".join(parts)} FROM raw."{table}"')
        row = cur.fetchone()
    return row[0], {
        c["name"]: {"filled": row[1 + i * 2], "distinct": row[2 + i * 2]}
        for i, c in enumerate(columns)
    }


def _digest(rows, width):
    """
    An order-independent checksum per column.

    Values are hashed through repr(), which both drivers agree on for the types
    in play, so the two sides are directly comparable. Adding rather than
    chaining means the row order the two databases return need not match.
    """
    totals = [0] * width
    mask = (1 << 64) - 1
    for row in rows:
        for index, value in enumerate(row):
            if value is None:
                continue
            digest = hashlib.md5(repr(value).encode("utf-8", "surrogatepass")).digest()
            totals[index] = (totals[index] + int.from_bytes(digest[:8], "big")) & mask
    return totals


def verify(conn, dst):
    failures = []
    checked = 0
    tables = source.tables(conn)

    with dst.cursor() as cur:
        cur.execute("SELECT table_name FROM information_schema.tables WHERE table_schema='raw'")
        present = {r[0] for r in cur.fetchall()} - BUILD_INPUTS
    if present != set(tables):
        failures.append(
            f"tables: missing {sorted(set(tables) - present)}, "
            f"unexpected {sorted(present - set(tables))}"
        )

    for table in tables:
        before = len(failures)
        columns = source.columns(conn, table)
        names = [c["name"] for c in columns]

        src_rows, src_cols = _source_stats(conn, table, columns)
        dst_rows, dst_cols = _target_stats(dst, table, columns)

        if src_rows != dst_rows:
            failures.append(f"{table}: {src_rows:,} rows in DB167, {dst_rows:,} in raw")
        for name in names:
            want, got = src_cols[name], dst_cols[name]
            if want["filled"] != got["filled"]:
                failures.append(
                    f'{table}."{name}": {want["filled"]:,} non-null in DB167, '
                    f'{got["filled"]:,} in raw'
                )
            if want["distinct"] != got["distinct"]:
                failures.append(
                    f'{table}."{name}": {want["distinct"]:,} distinct in DB167, '
                    f'{got["distinct"]:,} in raw'
                )

        def stream():
            for batch in source.rows(conn, table, names):
                yield from batch

        want_digest = _digest(stream(), len(names))
        with dst.cursor(name="digest") as cur:
            cur.itersize = 5000
            cur.execute(f'SELECT {", ".join(chr(34) + n + chr(34) for n in names)} '
                        f'FROM raw."{table}"')
            got_digest = _digest(cur, len(names))
        for index, name in enumerate(names):
            checked += 1
            if want_digest[index] != got_digest[index]:
                failures.append(f'{table}."{name}": values differ')

        mark = "ok" if len(failures) == before else "FAILED"
        print(f"  {table:<28} {src_rows:>8,} rows, {len(names):>2} columns  {mark}")

    with dst.cursor() as cur:
        cur.execute("""
            SELECT c.relname FROM pg_class c
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE n.nspname = 'raw' AND c.relkind = 'r'
              AND c.relname <> ALL (%s)
              AND NOT EXISTS (SELECT 1 FROM pg_constraint k
                              WHERE k.conrelid = c.oid AND k.contype = 'p')
        """, (list(BUILD_INPUTS),))
        without_pk = [r[0] for r in cur.fetchall()]
    if without_pk:
        failures.append(f"no primary key on: {without_pk}")

    try:
        with dst.cursor() as cur:
            cur.execute('DELETE FROM raw."SourceT" WHERE false')
        failures.append("raw accepted a write")
    except psycopg.errors.RaiseException:
        pass
    finally:
        dst.rollback()

    print(f"\n{checked:,} column checksums compared across {len(tables)} tables")
    if failures:
        print(f"\nFAILED -- {len(failures)} problems")
        for failure in failures:
            print("  -", failure)
        return 1
    print("PASSED -- raw matches DB167")
    return 0


def main():
    load_dotenv()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", action="store_true", help="write raw.sql and stop")
    parser.add_argument("--verify", action="store_true", help="verify and stop")
    args = parser.parse_args()

    conn = source.connect()

    if args.schema:
        SCHEMA_FILE.parent.mkdir(parents=True, exist_ok=True)
        SCHEMA_FILE.write_text(build_schema(conn))
        print(f"wrote {SCHEMA_FILE} ({len(source.tables(conn))} tables)")
        return 0

    with psycopg.connect(os.environ["DATABASE_URL"]) as dst:
        if not args.verify:
            load(conn, dst)
        return verify(conn, dst)


if __name__ == "__main__":
    sys.exit(main())
